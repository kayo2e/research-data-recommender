def build_fewshot_block(tbl: dict) -> str:
    """FEWSHOT에 있는 항목만 골라 "예시" 섹션 텍스트를 만든다. 없는 항목은 건너뛴다."""
    lines: list[str] = []
    for item, examples in FEWSHOT.items():
        if item not in tbl:
            continue
        name = tbl[item]["항목명"]
        lines.append(f"\n{item}({name}) 예시:")
        for ex in examples:
            if ex["quote"]:
                lines.append(f"  - {ex['label']}: \"{ex['quote']}\"")
            else:
                lines.append(f"  - {ex['label']}")
            lines.append(f"    이유: {ex['why']}")
    return "\n".join(lines)
